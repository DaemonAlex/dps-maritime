-- Find next available stacking position
function Config.FindNextStackPosition(existingContainers)
    local heightIncrement = Config.ContainerStacking.HeightIncrement
    local maxHeight = Config.ContainerStacking.MaxHeight
    local tolerance = Config.ContainerStacking.PositionTolerance

    for _, basePos in ipairs(Config.ContainerBasePositions) do
        local maxZ = basePos.z
        local stackFull = false

        -- Check existing containers at this position
        for _, container in ipairs(existingContainers) do
            if math.abs(basePos.x - container.x) < tolerance and
               math.abs(basePos.y - container.y) < tolerance then
                if container.z >= maxZ then
                    maxZ = container.z
                    if maxZ >= maxHeight then
                        stackFull = true
                    end
                end
            end
        end

        if not stackFull then
            return {
                x = basePos.x,
                y = basePos.y,
                z = maxZ + heightIncrement,
                heading = basePos.w
            }
        end
    end

    return nil -- All stacks full
end
